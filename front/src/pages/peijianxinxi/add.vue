				<el-input v-model="ruleForm.peijianzhonglei" 
					placeholder="产品种类" clearable :disabled=" false  ||ro.peijianzhonglei"></el-input>
			</el-form-item>
			<el-form-item class="add-item" label="品牌" prop="pinpai">
				<el-input v-model="ruleForm.pinpai" 
					placeholder="品牌" clearable :disabled=" false  ||ro.pinpai"></el-input>
			</el-form-item>
			<el-form-item class="add-item" label="数量" prop="shuliang">
				<el-input v-model.number="ruleForm.shuliang" 
					placeholder="数量" clearable :disabled=" false  ||ro.shuliang"></el-input>
			</el-form-item>
			<el-form-item class="add-item" label="售价" prop="shoujia">
				<el-input-number v-model="ruleForm.shoujia" placeholder="售价" :disabled=" false ||ro.shoujia"></el-input-number>
			</el-form-item>
			<el-form-item class="add-item" label="图片" v-if="type!='cross' || (type=='cross' && !ro.tupian)" prop="tupian">
				<file-upload
					tip="点击上传图片"
					action="file/upload"
					:limit="3"
					:multiple="true"
					:fileUrls="ruleForm.tupian?ruleForm.tupian:''"
					@change="tupianUploadChange"
					></file-upload>
			</el-form-item>
			<el-form-item class="add-item" v-else label="图片" prop="tupian">
				<img v-if="ruleForm.tupian.substring(0,4)=='http'" class="upload-img" v-bind:key="index" :src="ruleForm.tupian.split(',')[0]">
				<img v-else class="upload-img" v-bind:key="index" v-for="(item,index) in ruleForm.tupian.split(',')" :src="baseUrl+item">
			</el-form-item>
			<el-form-item class="add-item" label="登记日期" prop="dengjiriqi">
