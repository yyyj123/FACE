<script>
	export default {
		data() {
			return {
				id: '',
				baseUrl: '',
				ro:{
					peijianbianhao : false,
					peijianmingcheng : false,
					peijianzhonglei : false,
					pinpai : false,
					shuliang : false,
					shoujia : false,
					tupian : false,
					dengjiriqi : false,
					peijianjieshao : false,
				},
				type: '',
				userTableName: localStorage.getItem('UserTableName'),
				ruleForm: {
					peijianbianhao: this.getUUID(),
					peijianmingcheng: '',
					peijianzhonglei: '',
					pinpai: '',
					shuliang: '',
					shoujia: '',
					tupian: '',
					dengjiriqi: '',
					peijianjieshao: '',
				},


				rules: {
					peijianbianhao: [
					],
					peijianmingcheng: [
						{ required: true, message: '产品名称不能为空', trigger: 'blur' },
					],
					peijianzhonglei: [
						{ required: true, message: '产品种类不能为空', trigger: 'blur' },
					],
					pinpai: [
						{ required: true, message: '品牌不能为空', trigger: 'blur' },
					],
					shuliang: [
						{ required: true, message: '数量不能为空', trigger: 'blur' },
						{ validator: this.$validate.isIntNumer, trigger: 'blur' },
					],
					shoujia: [
						{ validator: this.$validate.isNumber, trigger: 'blur' },
					],
					tupian: [
					],
					dengjiriqi: [
					],
					peijianjieshao: [
					],
				},
				centerType: false,
			};
		},
		computed: {



		},
		components: {
		},
		created() {
			if(this.$route.query.centerType){
				this.centerType = true
			}
			//this.bg();
			let type = this.$route.query.type ? this.$route.query.type : '';
			this.init(type);
			this.baseUrl = this.$config.baseUrl;
			this.ruleForm.dengjiriqi = this.getCurDate()
		},
		methods: {
			getMakeZero(s) {
				return s < 10 ? '0' + s : s;
			},
			// 下载
			download(file){
				window.open(`${file}`)
			},
			// 初始化
			init(type) {
				this.type = type;
				if(type=='cross'){
					var obj = JSON.parse(localStorage.getItem('crossObj'));
					for (var o in obj){
						if(o=='peijianbianhao'){
							this.ruleForm.peijianbianhao = obj[o];
							this.ro.peijianbianhao = true;
							continue;
						}
						if(o=='peijianmingcheng'){
							this.ruleForm.peijianmingcheng = obj[o];
							this.ro.peijianmingcheng = true;
							continue;
						}
						if(o=='peijianzhonglei'){
							this.ruleForm.peijianzhonglei = obj[o];
							this.ro.peijianzhonglei = true;
							continue;
						}
						if(o=='pinpai'){
							this.ruleForm.pinpai = obj[o];
							this.ro.pinpai = true;
							continue;
						}
						if(o=='shuliang'){
							this.ruleForm.shuliang = obj[o];
							this.ro.shuliang = true;
							continue;
						}
						if(o=='shoujia'){
							this.ruleForm.shoujia = obj[o];
							this.ro.shoujia = true;
							continue;
						}
						if(o=='tupian'){
							this.ruleForm.tupian = obj[o].split(",")[0];
							this.ro.tupian = true;
							continue;
						}
						if(o=='dengjiriqi'){
							this.ruleForm.dengjiriqi = obj[o];
							this.ro.dengjiriqi = true;
							continue;
						}
						if(o=='peijianjieshao'){
							this.ruleForm.peijianjieshao = obj[o];
							this.ro.peijianjieshao = true;
							continue;
						}
					}
				}else if(type=='edit'){
					this.info()
				}
				// 获取用户信息
				this.$http.get(this.userTableName + '/session', {emulateJSON: true}).then(res => {
					if (res.data.code == 0) {
						var json = res.data.data;
					}
				});

				if (localStorage.getItem('raffleType') && localStorage.getItem('raffleType') != null) {
					localStorage.removeItem('raffleType')
					setTimeout(() => {
						this.onSubmit()
					}, 300)
				}
			},

			// 多级联动参数
			// 多级联动参数
			info() {
				this.$http.get(`peijianxinxi/detail/${this.$route.query.id}`, {emulateJSON: true}).then(res => {
					if (res.data.code == 0) {
						this.ruleForm = res.data.data;
					}
				});
			},
			// 提交
			async onSubmit() {
				if(this.ruleForm.peijianbianhao){
					this.ruleForm.peijianbianhao = String(this.ruleForm.peijianbianhao)
				}
				await this.$refs["ruleForm"].validate(async valid => {
					if(valid) {
						if(this.type=='cross'){
							var statusColumnName = localStorage.getItem('statusColumnName');
							var statusColumnValue = localStorage.getItem('statusColumnValue');
							if(statusColumnName && statusColumnName!='') {
								var obj = JSON.parse(localStorage.getItem('crossObj'));
								if(!statusColumnName.startsWith("[")) {
									for (var o in obj){
										if(o==statusColumnName){
											obj[o] = statusColumnValue;
										}
									}
									var table = localStorage.getItem('crossTable');
									await this.$http.post(table+'/update', obj).then(res => {});
								}
							}
						}


						await this.$http.post(`peijianxinxi/${this.ruleForm.id?'update':this.centerType?'save':'add'}`, this.ruleForm).then(async res => {
							if (res.data.code == 0) {
								this.$message({
									message: '操作成功',
									type: 'success',
									duration: 1500,
									onClose: () => {
										this.$router.go(-1);
										
									}
								});
							} else {
								this.$message({
									message: res.data.msg,
									type: 'error',
									duration: 1500
								});
							}
						});
					}
				});
			},
			// 获取uuid
			getUUID () {
				return new Date().getTime();
			},
			// 返回
			back() {
				this.$router.go(-1);
			},
			tupianUploadChange(fileUrls) {
				this.ruleForm.tupian = fileUrls.replace(new RegExp(this.$config.baseUrl,"g"),"");
			},
		}
	};
</script>

